/** User-imported word -> translation pairs. Loaded from SQLite at start and
 * updated whenever the user imports a new dictionary file. These override the
 * bundled dictionary so the reader shows the user's own translations inline. */
export const USER_DICTIONARY: Map<string, string> = new Map();

export function setUserDictionary(entries: { lemma: string; gloss: string }[]): void {
  USER_DICTIONARY.clear();
  for (const entry of entries) {
    const key = normalizeRussian(stripAccents(entry.lemma));
    if (key && entry.gloss.trim()) USER_DICTIONARY.set(key, entry.gloss.trim());
  }
}

export function addUserDictionaryEntry(lemma: string, gloss: string): void {
  const key = normalizeRussian(stripAccents(lemma));
  if (key && gloss.trim()) USER_DICTIONARY.set(key, gloss.trim());
}

export function removeUserDictionaryEntry(lemma: string): void {
  USER_DICTIONARY.delete(normalizeRussian(stripAccents(lemma)));
}

export function clearUserDictionary(): void {
  USER_DICTIONARY.clear();
}

export function ruEnLookup(normalizedForm: string): string | undefined {
  return USER_DICTIONARY.get(normalizedForm) ?? RU_EN_DICTIONARY.get(normalizedForm);
}